using AwesomeAssertions;
using Refitter.Core;
using Refitter.Tests.Build;
using Refitter.Tests.TestUtilities;

namespace Refitter.Tests.Scenarios;

/// <summary>
/// OpenAPI 3.2 QUERY operations. Refit has no QUERY verb attribute and Refit.QueryAttribute is the
/// parameter attribute, so the client gets its own HttpMethodAttribute subclass.
/// </summary>
[TestClass]
public class QueryOperationTests
{
    private const string OpenApiSpec = """
        {
          "openapi": "3.2.0",
          "info": { "title": "Items", "version": "v1" },
          "paths": {
            "/items": {
              "get": {
                "operationId": "GetItems",
                "parameters": [ { "name": "q", "in": "query", "required": true, "schema": { "type": "string" } } ],
                "responses": { "200": { "description": "ok", "content": { "application/json": { "schema": { "type": "array", "items": { "type": "string" } } } } } }
              },
              "query": {
                "operationId": "SearchItems",
                "requestBody": {
                  "required": true,
                  "content": { "application/json": { "schema": { "$ref": "#/components/schemas/SearchBody" } } }
                },
                "responses": { "200": { "description": "ok", "content": { "application/json": { "schema": { "type": "array", "items": { "type": "string" } } } } } }
              }
            }
          },
          "components": {
            "schemas": {
              "SearchBody": { "type": "object", "properties": { "q": { "type": "string" } } }
            }
          }
        }
        """;

    private static readonly string WithoutQuerySpec = OpenApiSpec
        .Replace("\"query\": {", "\"post\": {");

    private static readonly string DeprecatedQuerySpec = OpenApiSpec
        .Replace("\"operationId\": \"SearchItems\",", "\"operationId\": \"SearchItems\", \"deprecated\": true,");

    // A spec with a contract of the given name, referenced from the request body
    private static string WithContractNamed(string name) => OpenApiSpec
        .Replace("\"SearchBody\": {", $"\"{name}\": {{ \"type\": \"object\" }}, \"SearchBody\": {{")
        .Replace("\"properties\": { \"q\": { \"type\": \"string\" } }", $"\"properties\": {{ \"q\": {{ \"type\": \"string\" }}, \"a\": {{ \"$ref\": \"#/components/schemas/{name}\" }} }}");

    [TestMethod]
    public async Task Generates_QueryMethod_Attribute_On_Query_Operation()
    {
        var generatedCode = await GenerateCode();
        generatedCode.Should().Contain("[QueryMethodAttribute(\"/items\")]");
        generatedCode.Should().NotContain("[Query(\"/items\")]");
    }

    [TestMethod]
    public async Task Keeps_Query_Attribute_On_Query_Parameters()
    {
        var generatedCode = await GenerateCode();
        generatedCode.Should().Contain("[Query] string q");
    }

    [TestMethod]
    public async Task Generates_QueryMethodAttribute_Class()
    {
        var generatedCode = await GenerateCode();
        generatedCode.Should().Contain("public sealed class QueryMethodAttribute : global::Refit.HttpMethodAttribute");
        generatedCode.Should().Contain("public QueryMethodAttribute(string path) : base(path)");
        // The Refit source generator only inlines a verb constructed from a string literal. Anything else
        // falls back to reflection, and the RF006 warning is not reported for <auto-generated> files,
        // so a build cannot catch it: this assertion is the guard.
        generatedCode.Should().Contain("Method => new global::System.Net.Http.HttpMethod(\"QUERY\");");
    }

    [TestMethod]
    public async Task Does_Not_Generate_QueryMethodAttribute_Class_Without_Query_Operations()
    {
        var swaggerFile = await SwaggerFileHelper.CreateSwaggerJsonFile(WithoutQuerySpec);
        var sut = await RefitGenerator.CreateAsync(new RefitGeneratorSettings { OpenApiPath = swaggerFile });
        sut.Generate().Should().NotContain("QueryMethod");
    }

    [TestMethod]
    public async Task Generates_Internal_QueryMethodAttribute_For_Internal_Types()
    {
        var generatedCode = await GenerateCode(settings => settings.TypeAccessibility = TypeAccessibility.Internal);
        generatedCode.Should().Contain("internal sealed class QueryMethodAttribute : global::Refit.HttpMethodAttribute");
    }

    [TestMethod]
    [TestCategory("Integration")]
    [DataRow(true)]
    [DataRow(false)]
    public async Task Generates_QueryMethodAttribute_Only_When_Deprecated_Query_Operation_Is_Generated(bool generateDeprecatedOperations)
    {
        var generatedCode = await GenerateCode(
            settings => settings.GenerateDeprecatedOperations = generateDeprecatedOperations,
            DeprecatedQuerySpec);

        if (generateDeprecatedOperations)
        {
            generatedCode.Should().Contain("[QueryMethodAttribute(\"/items\")]");
            generatedCode.Should().Contain("sealed class QueryMethodAttribute");
            BuildHelper.BuildCSharp(generatedCode).Should().BeTrue();
        }
        else
        {
            generatedCode.Should().NotContain("QueryMethod");
        }
    }

    [TestMethod]
    [TestCategory("Integration")]
    public async Task Does_Not_Suffix_QueryMethodAttribute_With_ContractTypeSuffix()
    {
        var generatedCode = await GenerateCode(settings => settings.ContractTypeSuffix = "Dto");
        generatedCode.Should().Contain("class SearchBodyDto");
        generatedCode.Should().Contain("sealed class QueryMethodAttribute : global::Refit.HttpMethodAttribute");
        generatedCode.Should().Contain("[QueryMethodAttribute(\"/items\")]");
        BuildHelper.BuildCSharp(generatedCode).Should().BeTrue();
    }

    [TestMethod]
    [TestCategory("Integration")]
    [DataRow("")]
    [DataRow("Dto")]
    public async Task Renames_QueryMethodAttribute_When_A_Contract_Has_Its_Name(string contractTypeSuffix)
    {
        var generatedCode = await GenerateCode(
            settings => settings.ContractTypeSuffix = contractTypeSuffix,
            WithContractNamed("QueryMethodAttribute"));
        generatedCode.Should().Contain($"partial class QueryMethodAttribute{contractTypeSuffix}");
        generatedCode.Should().Contain("sealed class QueryMethod2Attribute : global::Refit.HttpMethodAttribute");
        generatedCode.Should().Contain("[QueryMethod2Attribute(\"/items\")]");
        BuildHelper.BuildCSharp(generatedCode).Should().BeTrue();
    }

    [TestMethod]
    [TestCategory("Integration")]
    public async Task Keeps_QueryMethodAttribute_Usage_When_A_Suffixed_Contract_Is_Named_QueryMethod()
    {
        var generatedCode = await GenerateCode(
            settings => settings.ContractTypeSuffix = "Dto",
            WithContractNamed("QueryMethod"));
        generatedCode.Should().Contain("partial class QueryMethodDto");
        generatedCode.Should().Contain("[QueryMethodAttribute(\"/items\")]");
        BuildHelper.BuildCSharp(generatedCode).Should().BeTrue();
    }

    [TestMethod]
    [TestCategory("Integration")]
    [DataRow(MultipleInterfaces.Unset, false)]
    [DataRow(MultipleInterfaces.ByEndpoint, false)]
    [DataRow(MultipleInterfaces.ByEndpoint, true)]
    public async Task Does_Not_Register_QueryMethodAttribute_As_Client(MultipleInterfaces multipleInterfaces, bool useGeneratedRefitClient)
    {
        var generatedCode = await GenerateCode(settings =>
        {
            settings.MultipleInterfaces = multipleInterfaces;
            settings.DependencyInjectionSettings = new DependencyInjectionSettings
            {
                BaseUrl = "https://example.com",
                UseGeneratedRefitClient = useGeneratedRefitClient,
            };
        });

        generatedCode.Should().Contain("AddRefit");
        generatedCode.Should().NotContain("<QueryMethodAttribute>");
        BuildHelper.BuildCSharp(generatedCode).Should().BeTrue();
    }

    [TestMethod]
    [TestCategory("Integration")]
    public async Task Can_Build_Generated_Code()
    {
        var generatedCode = await GenerateCode();
        BuildHelper.BuildCSharp(warningsAsErrors: true, generatedCode).Should().BeTrue();
    }

    [TestMethod]
    [TestCategory("Integration")]
    [DataRow(MultipleInterfaces.ByEndpoint)]
    [DataRow(MultipleInterfaces.ByTag)]
    public async Task Can_Build_Generated_Multiple_Files(MultipleInterfaces multipleInterfaces)
    {
        var swaggerFile = await SwaggerFileHelper.CreateSwaggerJsonFile(OpenApiSpec);
        var sut = await RefitGenerator.CreateAsync(
            new RefitGeneratorSettings
            {
                OpenApiPath = swaggerFile,
                MultipleInterfaces = multipleInterfaces,
                GenerateMultipleFiles = true,
            });

        var files = sut.GenerateMultipleFiles().Files;
        files.Should().ContainSingle(f => f.Filename == "QueryMethodAttribute.cs");
        BuildHelper.BuildCSharp(warningsAsErrors: true, files.Select(f => f.Content).ToArray()).Should().BeTrue();
    }

    private static async Task<string> GenerateCode(
        Action<RefitGeneratorSettings>? configure = null,
        string spec = OpenApiSpec)
    {
        var swaggerFile = await SwaggerFileHelper.CreateSwaggerJsonFile(spec);
        var settings = new RefitGeneratorSettings { OpenApiPath = swaggerFile };
        configure?.Invoke(settings);

        var sut = await RefitGenerator.CreateAsync(settings);
        return sut.Generate();
    }
}
